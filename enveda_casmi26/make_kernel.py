"""Bundle the package into one Kaggle script kernel: python -m enveda_casmi26.make_kernel OUTDIR."""

import json
import os
import sys
from pathlib import Path

PKG = Path(__file__).parent
MODULES = ["__init__", "chem", "library", "search", "model", "rank", "submission", "predict"]
SLUG = "casmi26-original-library-search"
DATASET = "danielaijdkx/casmi26-own-candidates-and-model"


def main(outdir):
    os.makedirs(outdir, exist_ok=True)
    parts = ["# Enveda CASMI 2026 - original library-search solution (generated by make_kernel.py)\n",
             "import os, sys\nos.makedirs('/kaggle/working/enveda_casmi26', exist_ok=True)\n"]
    for m in MODULES:
        src = (PKG / f"{m}.py").read_text()
        parts.append(f"open('/kaggle/working/enveda_casmi26/{m}.py', 'w').write({src!r})\n")
    parts.append("sys.path.insert(0, '/kaggle/working')\n"
                 "from enveda_casmi26.predict import main\nmain()\n")
    Path(outdir, f"{SLUG}.py").write_text("".join(parts))
    meta = {
        "id": f"danielaijdkx/{SLUG}", "title": "CASMI26 original library search",
        "code_file": f"{SLUG}.py", "language": "python", "kernel_type": "script",
        "is_private": True, "enable_gpu": False, "enable_tpu": False, "enable_internet": False,
        "dataset_sources": [DATASET], "kernel_sources": [], "model_sources": [],
        "competition_sources": ["enveda-CASMI26-molecule-id-mass-spectra"],
    }
    Path(outdir, "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    print("wrote", outdir)


if __name__ == "__main__":
    main(sys.argv[1])
