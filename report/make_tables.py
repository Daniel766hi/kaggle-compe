"""Write the report's result tables (LaTeX) from one or more trial_summary.csv files.

    python report/make_tables.py runs/chi-pilot/trial_summary.csv runs/baseline/trial_summary.csv
    python report/make_tables.py --main chi-pilot-audit1 runs/*/trial_summary.csv

Each file comes from one run of notebooks/chi_pilot_run.py (or ``python -m chi_pilot.results``)
and carries its configuration in the ``label`` column. Writes ``report/results.tex`` with the
main results table and the most frequent failed checks of the main configuration. With no input
files it writes placeholder tables, so the report always compiles.
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
from chi_pilot.results import TRACKS, failed_check_counts, metrics, read_summary  # noqa: E402

TRACK_NAMES = {"pa_provider": "Provider PA", "pa_um": "Payer UM", "cm": "Care Mgmt."}


def tex_escape(text: str) -> str:
    for char, repl in (("\\", r"\textbackslash{}"), ("_", r"\_"), ("&", r"\&"), ("%", r"\%"),
                       ("#", r"\#"), ("$", r"\$"), ("^", r"\^{}")):
        text = text.replace(char, repl)
    return text


def _pct(value: float | None) -> str:
    return "--" if value is None else f"{100 * value:.1f}"


def results_table(rows: list[dict]) -> str:
    labels = list(dict.fromkeys(r["label"] for r in rows))
    lines = [
        r"\begin{table*}[t]",  # spans both columns: nine columns do not fit in one
        r"\centering",
        r"\caption{Public development set results (pass@1, \%). CI: 95\% task-level bootstrap.}",
        r"\label{tab:results}",
        r"\begin{tabular}{lcccccccc}",
        r"\toprule",
        r"Configuration & " + " & ".join(TRACK_NAMES[t] for t in TRACKS)
        + r" & Overall & 95\% CI & pass$^3$ & \$/task & Tools \\",
        r"\midrule",
    ]
    if not labels:
        lines.append(r"\multicolumn{9}{c}{\emph{Pending: no runs yet.}} \\")
    for label in labels:
        sub = [r for r in rows if r["label"] == label]
        per_track = [metrics(sub, t) for t in TRACKS]
        overall = metrics(sub)
        cells = [_pct(m["pass_at_1"]) if m["n_tasks"] else "--" for m in per_track]
        cost = overall["mean_cost_usd"]
        tools = overall["mean_tool_calls"]
        lines.append(
            f"{tex_escape(label)} & " + " & ".join(cells)
            + f" & {_pct(overall['pass_at_1'])}"
            + f" & [{_pct(overall['ci_low'])}, {_pct(overall['ci_high'])}]"
            + f" & {_pct(overall['pass_pow_3'])}"
            + f" & {'--' if cost is None else f'{cost:.2f}'}"
            + f" & {'--' if tools is None else f'{tools:.0f}'} \\\\"
        )
    n_tasks = sorted({metrics([r for r in rows if r['label'] == l])["n_tasks"] for l in labels})
    lines += [r"\bottomrule", r"\end{tabular}"]
    if n_tasks and n_tasks != [75]:
        lines.append(r"\par\vspace{2pt}{\footnotesize Tasks per configuration: "
                     + ", ".join(map(str, n_tasks)) + r" (75 = full public set).}")
    lines.append(r"\end{table*}")
    return "\n".join(lines)


def failed_checks_table(rows: list[dict], label: str | None, top: int = 10) -> str:
    sub = [r for r in rows if r["label"] == label] if label else []
    first = [r for r in sub if r["attempt"] == 1]
    counts: Counter = failed_check_counts(sub)
    lines = [
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Most frequent failed verifier checks (" + tex_escape(label or "main run")
        + r", first attempts).}",
        r"\label{tab:failures}",
        r"\scriptsize",  # check names are long and set in typewriter type
        r"\begin{tabular}{@{}lr@{}}",
        r"\toprule",
        r"Check & Failed trials \\",
        r"\midrule",
    ]
    if not counts:
        lines.append(r"\multicolumn{2}{c}{\emph{Pending: no failed checks recorded yet.}} \\")
    for check, n in counts.most_common(top):
        lines.append(f"\\texttt{{{tex_escape(check)}}} & {n}/{len(first)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("summaries", nargs="*", type=Path, help="trial_summary.csv files")
    parser.add_argument("--main", help="label of the main configuration (default: first file's)")
    parser.add_argument("--out", type=Path, default=REPO / "report" / "results.tex")
    args = parser.parse_args(argv)

    rows = [row for path in args.summaries for row in read_summary(path)]
    main_label = args.main or (rows[0]["label"] if rows else None)
    args.out.write_text(
        "% Generated by report/make_tables.py; do not edit by hand.\n"
        + results_table(rows) + "\n\n" + failed_checks_table(rows, main_label) + "\n"
    )
    print(f"wrote {args.out} ({len(rows)} trials, main configuration: {main_label})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
